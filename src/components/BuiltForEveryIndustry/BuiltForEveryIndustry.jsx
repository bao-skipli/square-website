import React, { Component } from "react";
import SplitText from "../common/SplitText/SplitText";
import "./BuiltForEveryIndustry.css";

const industryItems = [
  {
    id: "services",
    label: "Services",
    image: "/images/industries/PD07746_-_services.avif",
    svg: "/images/industries/services.svg",
    stat: "$93 billion+",
    subtitle: "paid with invoices globally",
    linkText: "Learn more",
    linkUrl: "#services",
    alt: "Craftsperson working in services workshop",
  },
  {
    id: "retail",
    label: "Retail",
    image: "/images/industries/PD07746_-_retail.avif",
    svg: "/images/industries/retail.svg",
    stat: "$39 billion+",
    subtitle: "generated by retailers using Square annually",
    linkText: "Learn more",
    linkUrl: "#retail",
    alt: "Retail shop staff with customer",
  },
  {
    id: "food-bev",
    label: "Food &\nBeverage",
    image: "/images/industries/PD07746_-_food_and_bev.avif",
    svg: "/images/industries/food-bev.svg",
    stat: "450,000+",
    subtitle: "food and beverage sellers using Square globally",
    linkText: "Learn more",
    linkUrl: "#food-and-beverage",
    alt: "Kitchen chef preparing food",
  },
  {
    id: "beauty",
    label: "Beauty",
    image: "/images/industries/PD07746_-_beauty.avif",
    svg: "/images/industries/beauty.svg",
    stat: "15 million+",
    subtitle: "appointments booked through Square globally every month",
    linkText: "Learn more",
    linkUrl: "#beauty",
    alt: "Beauty specialist smiling with client",
  },
];

export default class BuiltForEveryIndustry extends Component {
  constructor(props) {
    super(props);
    this.state = {
      activeIndex: 0,
      scale: 0.8,
    };
    this.sectionRef = React.createRef();
    this.cardRefs = [];
  }

  componentDidMount() {
    window.addEventListener("scroll", this.handleScroll, { passive: true });
    window.addEventListener("resize", this.handleScroll);
    this.handleScroll();

    const defaultCard = this.cardRefs[0];
    if (defaultCard) {
      const rect = defaultCard.getBoundingClientRect();
      defaultCard.style.setProperty("--mouse-x", `${(rect.width || 560) / 2}px`);
      defaultCard.style.setProperty("--mouse-y", `${(rect.height || 640) * 0.38}px`);
    }
  }

  componentWillUnmount() {
    window.removeEventListener("scroll", this.handleScroll);
    window.removeEventListener("resize", this.handleScroll);
  }

  handleScroll = () => {
    if (!this.sectionRef.current) return;
    const rect = this.sectionRef.current.getBoundingClientRect();
    const windowHeight = window.innerHeight;

    const startTrigger = windowHeight * 0.95;
    const endTrigger = windowHeight * 0.35;

    if (rect.top >= startTrigger) {
      this.setState({ scale: 0.8 });
    } else if (rect.top <= endTrigger) {
      this.setState({ scale: 1.0 });
    } else {
      const progress = (startTrigger - rect.top) / (startTrigger - endTrigger);
      const clamped = Math.max(0, Math.min(1, progress));
      const currentScale = 0.8 + clamped * 0.2;
      this.setState({ scale: parseFloat(currentScale.toFixed(4)) });
    }
  };

  handleMouseMove = (e, index) => {
    const card = this.cardRefs[index];
    if (!card) return;
    const rect = card.getBoundingClientRect();
    const x = e.clientX - rect.left;
    const y = e.clientY - rect.top;
    card.style.setProperty("--mouse-x", `${x}px`);
    card.style.setProperty("--mouse-y", `${y}px`);
  };

  handleMouseEnter = (e, index) => {
    this.setState({ activeIndex: index });
    const card = this.cardRefs[index];
    if (card) {
      const rect = card.getBoundingClientRect();
      const x = e.clientX ? e.clientX - rect.left : rect.width / 2;
      const y = e.clientY ? e.clientY - rect.top : rect.height * 0.38;
      card.style.setProperty("--mouse-x", `${x}px`);
      card.style.setProperty("--mouse-y", `${y}px`);
    }
  };

  render() {
    const { activeIndex, scale } = this.state;

    return (
      <section
        ref={this.sectionRef}
        className="built-for-every-industry"
        id="industries"
        aria-label="Built for every industry"
      >
        <div className="bfei-container">
          <div className="bfei-header">
            <div className="bfei-eyebrow">
              <SplitText start={10} end={50}>
                BUILT FOR EVERY INDUSTRY
              </SplitText>
            </div>

            <h2 className="bfei-title">
              <SplitText start={10} end={50}>
                Keep your business growing
              </SplitText>
            </h2>
          </div>

          <div
            className="bfei-cards-track"
            style={{
              transform: `scale(${scale})`,
            }}
          >
            {industryItems.map((item, index) => {
              const isActive = activeIndex === index;

              return (
                <article
                  key={item.id}
                  ref={(el) => {
                    this.cardRefs[index] = el;
                  }}
                  className={`bfei-card ${isActive ? "is-active" : ""}`}
                  onClick={(e) => this.handleMouseEnter(e, index)}
                  onMouseEnter={(e) => this.handleMouseEnter(e, index)}
                  onMouseMove={(e) => this.handleMouseMove(e, index)}
                >
                  <img
                    src={item.image}
                    alt={item.alt}
                    className="bfei-card-bg"
                    loading={index < 2 ? "eager" : "lazy"}
                  />

                  <div className="bfei-card-overlay" />

                  <div className="bfei-inactive-title">
                    {item.label}
                  </div>

                  {isActive && (
                    <div className="bfei-floating-svg">
                      <img
                        src={item.svg}
                        alt={`${item.label} typography`}
                        className="bfei-svg-image"
                      />
                    </div>
                  )}

                  <div className="bfei-bottom-content">
                    <div className="bfei-divider" />
                    <div className="bfei-info-row">
                      <div className="bfei-stat-block">
                        <div className="bfei-stat">{item.stat}</div>
                        <div className="bfei-subtitle">{item.subtitle}</div>
                      </div>
                      <a
                        href={item.linkUrl}
                        className="bfei-link"
                      >
                        {item.linkText}
                      </a>
                    </div>
                  </div>
                </article>
              );
            })}
          </div>
        </div>
      </section>
    );
  }
}
